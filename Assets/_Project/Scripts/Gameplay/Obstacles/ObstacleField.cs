using System;
using System.Collections.Generic;

namespace BubbleAscent.Gameplay
{
    public enum ObstacleKind
    {
        Crosser,
        Gate,
    }

    /// <summary>One obstacle band at height Y. Gates use GapHalf; crossers use HalfWidth/PatrolHalf/Speed/Phase.</summary>
    public struct Obstacle
    {
        public ObstacleKind Kind;
        public float Y;
        public float HalfThickness;
        public float GapHalf;
        public float HalfWidth;
        public float PatrolHalf;
        public float Speed;
        public float Phase;
    }

    /// <summary>
    /// Obstacles generated by height (crossers and gates), the difficulty curve and circle-vs-rectangle collision.
    /// Every generated obstacle is passable by construction: see MinFairGap, FairPatrolHalf and MinFairSpacing.
    /// </summary>
    public class ObstacleField
    {
        const int InitialCapacity = 64;
        const float MinSpacingFloor = 0.1f;

        readonly ObstacleSettings _settings;
        readonly BubbleSettings _bubble;
        readonly List<Obstacle> _obstacles = new List<Obstacle>(InitialCapacity);
        Random _rng;
        float _nextY;

        public IReadOnlyList<Obstacle> Obstacles => _obstacles;

        public ObstacleField(ObstacleSettings settings, BubbleSettings bubble)
        {
            _settings = settings ?? throw new ArgumentNullException(nameof(settings));
            _bubble = bubble ?? throw new ArgumentNullException(nameof(bubble));
            Reset(0);
        }

        /// <param name="seed">Layout seed: the same seed always gives the same obstacles.</param>
        public void Reset(int seed)
        {
            _rng = new Random(seed);
            _obstacles.Clear();
            _nextY = _settings.firstObstacleHeight;
        }

        /// <summary>0 at the start, 1 at hardestAtHeight and above.</summary>
        public float Difficulty(float height)
        {
            if (_settings.hardestAtHeight <= 0f) return 1f;
            return Numeric.Clamp01(height / _settings.hardestAtHeight);
        }

        // ---- Fairness ----
        // The player can only change size at a finite rate, so the generator never asks for the impossible:
        //  - a gate gap always fits the smallest bubble plus a margin (MinFairGap);
        //  - a crosser's patrol always leaves a window beside it for the largest bubble (FairPatrolHalf);
        //  - consecutive obstacles are at least one thickest obstacle plus the largest bubble's diameter apart
        //    (MinFairSpacing), so the bubble can always be between two of them.
        // Tuning that violates these is raised to the fair value here, whatever the asset says.

        /// <summary>Fair spacing at a height: never below minSpacing nor below MinFairSpacing.</summary>
        public float SpacingAt(float height) =>
            Math.Max(Math.Max(_settings.minSpacing, MinFairSpacing),
                Numeric.Lerp(_settings.spacingEasy, _settings.spacingHard, Difficulty(height)));

        /// <summary>Thickest obstacle plus the max bubble diameter: room to pass between any two.</summary>
        public float MinFairSpacing => FairSpacing(_settings, _bubble);

        /// <summary>Fair gate gap (full width) at a height: always fits the min bubble plus margin.</summary>
        public float GateGapAt(float height) =>
            Math.Max(MinFairGap, Numeric.Lerp(_settings.gateGapEasy, _settings.gateGapHard, Difficulty(height)));

        public float MinFairGap => FairGap(_settings, _bubble);

        /// <summary>Fair patrol half width: leaves a free window even for the max bubble.</summary>
        public float FairPatrolHalf => Math.Max(_settings.crosserPatrolHalfWidth, FairPatrolFloor(_settings, _bubble));

        // The rules themselves, static so the tuning asset's validation uses the very same definition.

        /// <summary>Smallest fair gate gap: the min bubble's diameter plus the margin.</summary>
        public static float FairGap(ObstacleSettings o, BubbleSettings b) => 2f * b.minRadius + o.gateMargin;

        /// <summary>Smallest fair spacing: the thickest obstacle plus the max bubble's diameter.</summary>
        public static float FairSpacing(ObstacleSettings o, BubbleSettings b) =>
            Math.Max(MinSpacingFloor, Math.Max(o.gateThickness, o.crosserThickness) + 2f * b.maxRadius);

        /// <summary>Smallest fair patrol half width: a free window beside the crosser for the max bubble.</summary>
        public static float FairPatrolFloor(ObstacleSettings o, BubbleSettings b) =>
            o.crosserWidth * 0.5f + b.maxRadius + o.crosserMargin;

        /// <summary>Generates obstacles until the next one would be above y.</summary>
        public void EnsureAbove(float y)
        {
            while (_nextY <= y)
            {
                _obstacles.Add(Create(_nextY));
                _nextY += SpacingAt(_nextY);
            }
        }

        /// <summary>Discards obstacles that lie entirely below y.</summary>
        public void TrimBelow(float y)
        {
            int remove = 0;
            while (remove < _obstacles.Count &&
                   _obstacles[remove].Y + _obstacles[remove].HalfThickness < y) remove++;
            if (remove > 0) _obstacles.RemoveRange(0, remove);
        }

        /// <summary>Crosser center x at run time t: a triangle wave between +-PatrolHalf.</summary>
        public static float CrosserX(in Obstacle o, float time)
        {
            float span = 2f * o.PatrolHalf;
            if (span <= 0f) return 0f;
            float d = (o.Phase + o.Speed * time) % (2f * span);
            if (d < 0f) d += 2f * span;
            return d <= span ? -o.PatrolHalf + d : o.PatrolHalf - (d - span);
        }

        /// <summary>True if a circle at (cx, cy) with radius r touches any obstacle at run time t.</summary>
        public bool Overlaps(float cx, float cy, float r, float time)
        {
            for (int i = 0; i < _obstacles.Count; i++)
            {
                Obstacle o = _obstacles[i];
                float bottom = o.Y - o.HalfThickness;
                float top = o.Y + o.HalfThickness;
                if (cy + r < bottom || cy - r > top) continue;

                if (o.Kind == ObstacleKind.Gate)
                {
                    // Two walls: (-inf, -GapHalf] and [GapHalf, +inf).
                    if (CircleRect(cx, cy, r, float.NegativeInfinity, -o.GapHalf, bottom, top)) return true;
                    if (CircleRect(cx, cy, r, o.GapHalf, float.PositiveInfinity, bottom, top)) return true;
                }
                else
                {
                    float x = CrosserX(o, time);
                    if (CircleRect(cx, cy, r, x - o.HalfWidth, x + o.HalfWidth, bottom, top)) return true;
                }
            }
            return false;
        }

        Obstacle Create(float y)
        {
            float difficulty = Difficulty(y);
            var o = new Obstacle { Y = y };
            if (_rng.NextDouble() < Numeric.Lerp(_settings.gateChanceEasy, _settings.gateChanceHard, difficulty))
            {
                o.Kind = ObstacleKind.Gate;
                o.HalfThickness = _settings.gateThickness * 0.5f;
                o.GapHalf = GateGapAt(y) * 0.5f;
            }
            else
            {
                o.Kind = ObstacleKind.Crosser;
                o.HalfThickness = _settings.crosserThickness * 0.5f;
                o.HalfWidth = _settings.crosserWidth * 0.5f;
                o.PatrolHalf = FairPatrolHalf;
                o.Speed = Numeric.Lerp(_settings.crosserSpeedEasy, _settings.crosserSpeedHard, difficulty);
                o.Phase = (float)_rng.NextDouble() * 4f * o.PatrolHalf;
            }
            return o;
        }

        static bool CircleRect(float cx, float cy, float r, float xMin, float xMax, float yMin, float yMax)
        {
            float nx = cx < xMin ? xMin : (cx > xMax ? xMax : cx);
            float ny = cy < yMin ? yMin : (cy > yMax ? yMax : cy);
            float dx = cx - nx, dy = cy - ny;
            return dx * dx + dy * dy < r * r;
        }

    }
}
